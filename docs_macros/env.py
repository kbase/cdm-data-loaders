def render_reference_table(
    table_id: str,
    *,
    templates_dir: Path = TEMPLATES_DIR,
) -> str:
    """Render an individual reference table template from ``TABLE_TEMPLATE_REGISTRY``.

    :param table_id: Canonical reference table identifier (e.g. ``"xsv_config_table"``).
    :type table_id: str
    :param templates_dir: Root directory containing ``.md.j2`` templates.
    :type templates_dir: Path
    :return: Rendered Markdown table string without trailing blank lines.
    :rtype: str
    """
    env = create_jinja_env(templates_dir)
    table_ctx = build_table_context(table_id)
    rendered = env.get_template(table_ctx.template).render(
        headers=table_ctx.headers,
        rows=table_ctx.rows,
    )
    return rendered.rstrip()


def discover_spec_names(specs_root: Path) -> tuple[str, ...]:
    """Return sorted specification directory names containing ``rules.yaml`` under ``specs_root``.

    :param specs_root: Root directory containing converter or pipeline specification subdirectories.
    :type specs_root: Path
    :return: Sorted tuple of directory names containing ``rules.yaml``.
    :rtype: tuple[str, ...]
    """
    if not specs_root.is_dir():
        return ()
    return tuple(sorted(p.name for p in specs_root.iterdir() if p.is_dir() and (p / "rules.yaml").is_file()))


def render_macro_stub(
    macro_call: str,
    *,
    templates_dir: Path = TEMPLATES_DIR,
) -> str:
    """Render a ``render_macros: true`` Markdown stub file from ``pages/macro_stub.md.j2``.

    :param macro_call: Jinja macro invocation expression (e.g. ``'render_converter_spec("xsd_to_pyarrow")'``).
    :type macro_call: str
    :param templates_dir: Root directory containing ``.md.j2`` templates.
    :type templates_dir: Path
    :return: Rendered 4-line Markdown stub ending with a single newline.
    :rtype: str
    """
    return _render_page_template(
        "pages/macro_stub.md.j2",
        templates_dir=templates_dir,
        macro_call=macro_call,
    )


def build_generated_docs_plan(
    paths: DocsGenerationPaths = DEFAULT_GENERATION_PATHS,
    *,
    include_static_pages: bool = True,
) -> dict[Path, str]:
    """Compute the mapping of relative paths under ``docs/`` to autogenerated file contents.

    :param paths: Filesystem roots for specs, package schemas, and Jinja2 templates.
    :type paths: DocsGenerationPaths
    :param include_static_pages: Whether to include ``cli_reference.md`` and ``bundled_schemas.md``.
    :type include_static_pages: bool
    :return: Ordered mapping of ``docs/``-relative ``Path`` keys to UTF-8 text contents.
    :rtype: dict[Path, str]
    """
    plan: dict[Path, str] = {}
    if include_static_pages:
        for stub_name, macro_call in (
            ("cli_reference.md", "render_cli_reference()"),
            ("bundled_schemas.md", "render_bundled_schemas()"),
        ):
            plan[Path(stub_name)] = render_macro_stub(macro_call, templates_dir=paths.templates_dir)

    for specs_root, macro_name in (
        (paths.converter_specs_root, "render_converter_spec"),
        (paths.pipeline_specs_root, "render_pipeline_spec"),
    ):
        for spec_name in discover_spec_names(specs_root):
            plan[Path(f"{spec_name}_specification.md")] = render_macro_stub(
                f'{macro_name}("{spec_name}")',
                templates_dir=paths.templates_dir,
            )

    if (paths.src_root / SCHEMAS_SUBDIR).is_dir():
        for asset in discover_schema_assets(src_root=paths.src_root, repo_root=paths.repo_root):
            if asset.published_rel_path is not None:
                plan[asset.published_rel_path] = (paths.src_root / asset.rel_path).read_text(encoding="utf-8")

    return plan


def _prune_empty_dirs(root: Path) -> None:
    """Remove empty subdirectories inside ``root`` bottom-up, including ``root`` if empty.

    :param root: Root directory to prune.
    :type root: Path
    :return: None.
    :rtype: None
    """
    if not root.is_dir():
        return
    for subdir in sorted((p for p in root.rglob("*") if p.is_dir()), reverse=True):
        if not any(subdir.iterdir()):
            subdir.rmdir()
    if not any(root.iterdir()):
        root.rmdir()


def _prune_stale_generated_docs(
    docs_dir: Path,
    expected_resolved: set[Path],
    *,
    check: bool,
) -> tuple[list[Path], list[Path]]:
    """Find and optionally delete stale macro stubs and published schemas under ``docs_dir``.

    :param docs_dir: Target ``docs/`` directory.
    :type docs_dir: Path
    :param expected_resolved: Set of resolved file paths expected by the current generation plan.
    :type expected_resolved: set[Path]
    :param check: When ``True``, collect stale paths without modifying disk.
    :type check: bool
    :return: Pair of ``(removed_paths, drifted_paths)``.
    :rtype: tuple[list[Path], list[Path]]
    """
    stale_candidates: list[Path] = [
        md_candidate
        for md_candidate in sorted(docs_dir.glob("*.md"))
        if md_candidate.is_file()
        and md_candidate.resolve() not in expected_resolved
        and GENERATED_MACRO_STUB_RE.search(md_candidate.read_text(encoding="utf-8"))
    ]
    schemas_dir = docs_dir / SCHEMAS_SUBDIR
    if schemas_dir.is_dir():
        stale_candidates.extend(
            schema_candidate
            for schema_candidate in sorted(schemas_dir.rglob("*"))
            if schema_candidate.is_file() and schema_candidate.resolve() not in expected_resolved
        )

    if check:
        return [], stale_candidates

    for stale_path in stale_candidates:
        stale_path.unlink()
    _prune_empty_dirs(schemas_dir)
    return stale_candidates, []


def sync_generated_docs(
    paths: DocsGenerationPaths = DEFAULT_GENERATION_PATHS,
    *,
    include_static_pages: bool = True,
    check: bool = False,
    prune_stale: bool = True,
) -> GeneratedDocsSyncResult:
    """Generate, update, or verify all autogenerated stubs and published schemas under ``paths.docs_dir``.

    :param paths: Filesystem roots for ``docs/``, specs, package schemas, and Jinja2 templates.
    :type paths: DocsGenerationPaths
    :param include_static_pages: Whether to include ``cli_reference.md`` and ``bundled_schemas.md``.
    :type include_static_pages: bool
    :param check: When ``True``, inspect without modifying disk and record out-of-sync files in ``drifted_paths``.
    :type check: bool
    :param prune_stale: When ``True``, remove or report orphaned macro stubs and published schema files.
    :type prune_stale: bool
    :return: Synchronization summary with expected, written, removed, and drifted file paths.
    :rtype: GeneratedDocsSyncResult
    """
    plan = build_generated_docs_plan(paths, include_static_pages=include_static_pages)
    expected_paths: list[Path] = []
    written_paths: list[Path] = []
    drifted_paths: list[Path] = []

    for rel_path, expected_text in plan.items():
        target = paths.docs_dir / rel_path
        expected_paths.append(target)
        current_text = target.read_text(encoding="utf-8") if target.is_file() else None
        if current_text != expected_text:
            if check:
                drifted_paths.append(target)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(expected_text, encoding="utf-8")
                written_paths.append(target)

    removed_paths: list[Path] = []
    if prune_stale and paths.docs_dir.is_dir():
        expected_resolved = {p.resolve() for p in expected_paths}
        pruned, stale_drifted = _prune_stale_generated_docs(paths.docs_dir, expected_resolved, check=check)
        removed_paths.extend(pruned)
        drifted_paths.extend(stale_drifted)

    return GeneratedDocsSyncResult(
        expected_paths=tuple(expected_paths),
        written_paths=tuple(written_paths),
        removed_paths=tuple(removed_paths),
        drifted_paths=tuple(drifted_paths),
    )


def clean_generated_docs(paths: DocsGenerationPaths = DEFAULT_GENERATION_PATHS) -> tuple[Path, ...]:
    """Remove all autogenerated Markdown stubs and published schemas from ``paths.docs_dir``.

    :param paths: Filesystem roots for ``docs/``, specs, package schemas, and Jinja2 templates.
    :type paths: DocsGenerationPaths
    :return: Sorted tuple of removed ``Path`` objects.
    :rtype: tuple[Path, ...]
    """
    if not paths.docs_dir.is_dir():
        return ()

    plan = build_generated_docs_plan(paths)
    removed: dict[Path, Path] = {}
    for rel_path in plan:
        target = paths.docs_dir / rel_path
        if target.is_file():
            resolved = target.resolve()
            target.unlink()
            removed[resolved] = target

    pruned, _ = _prune_stale_generated_docs(paths.docs_dir, set(), check=False)
    for path in pruned:
        removed[path.resolve()] = path

    return tuple(sorted(removed.values()))
